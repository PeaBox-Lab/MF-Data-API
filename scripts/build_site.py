"""Copy the documentation site into the exported static tree.

Usage:
    python scripts/build_site.py --out public --repo-url https://github.com/you/MFAPI

The script switches ``assets/config.js`` to static mode so the same pages work on
GitHub Pages or any plain file host (paths gain a ``.json`` suffix).
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

from build_sitemap import DEFAULT_BASE_URL, write_sitemap

ROOT = Path(__file__).resolve().parent.parent


def build(
    out: Path,
    repo_url: str = "",
    api_base: str = "api/v1",
    base_url: str = DEFAULT_BASE_URL,
) -> None:
    web = ROOT / "web"
    out.mkdir(parents=True, exist_ok=True)
    shutil.copytree(web, out, dirs_exist_ok=True)

    sitemap_entries = write_sitemap(web, out / "sitemap.xml", base_url=base_url)

    config = (
        "/* Generated by scripts/build_site.py - static JSON mode. */\n"
        "window.MFDATA_CONFIG = "
        + json.dumps(
            {
                "mode": "static",
                "apiBase": api_base,
                "repoUrl": repo_url,
            },
            indent=2,
        )
        + ";\n"
    )
    (out / "assets" / "config.js").write_text(config, encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    print(
        f"Built static site in {out} "
        f"(apiBase={api_base!r}, repoUrl={repo_url!r}, sitemapURLs={len(sitemap_entries)})"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="public", help="Output directory")
    parser.add_argument("--repo-url", default="", help="Repository URL shown in the UI")
    parser.add_argument(
        "--api-base",
        default="api/v1",
        help="Relative API base for static hosting (default: api/v1)",
    )
    parser.add_argument(
        "--base-url",
        default=DEFAULT_BASE_URL,
        help="Canonical site URL used in sitemap.xml",
    )
    args = parser.parse_args()
    build(
        Path(args.out),
        repo_url=args.repo_url,
        api_base=args.api_base,
        base_url=args.base_url,
    )


if __name__ == "__main__":
    main()
